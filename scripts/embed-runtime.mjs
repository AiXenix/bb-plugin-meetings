// Embeds runtime/** (bot runner, transcriber, mock meeting page) into
// src/generated/runtime-files.ts. The host bundle must be self-contained: the
// plugin directory is not available on remote machines, so the runtime ships
// as strings and the host writes it into its data directory.
// Run `npm run embed` after editing anything under runtime/; a test checks it.
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const runtimeDir = join(root, "runtime");
export const generatedPath = join(root, "src", "generated", "runtime-files.ts");

/** Files that are not part of the shipped runtime (tests, caches, local artifacts). */
function shipped(relPath) {
  const name = relPath.split("/").pop() ?? "";
  if (relPath.split("/").some((part) => part === "__pycache__" || part === "node_modules" || part.startsWith("."))) {
    return false;
  }
  if (/^test_.*\.py$/.test(name) || /\.test\.m?js$/.test(name)) return false;
  return /\.(mjs|js|py|html|css|json|txt)$/.test(name);
}

export function collectRuntimeFiles(dir = runtimeDir) {
  const files = {};
  const walk = (current) => {
    for (const entry of readdirSync(current).sort()) {
      const full = join(current, entry);
      const rel = relative(dir, full).split(sep).join("/");
      if (statSync(full).isDirectory()) {
        if (shipped(`${rel}/x.js`)) walk(full);
      } else if (shipped(rel)) {
        const buffer = readFileSync(full);
        files[rel] = buffer.toString("utf8");
      }
    }
  };
  walk(dir);
  return files;
}

export function renderRuntimeFiles(files) {
  const hash = createHash("sha256");
  for (const [rel, content] of Object.entries(files)) hash.update(rel).update("\0").update(content).update("\0");
  const digest = hash.digest("hex").slice(0, 16);
  return [
    "// Generated by scripts/embed-runtime.mjs from runtime/**. Do not edit.",
    `export const RUNTIME_HASH = ${JSON.stringify(digest)};`,
    `export const RUNTIME_FILES: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 1)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(dirname(generatedPath), { recursive: true });
  const files = collectRuntimeFiles();
  writeFileSync(generatedPath, renderRuntimeFiles(files));
  console.log(`wrote ${generatedPath} (${Object.keys(files).length} files)`);
}
